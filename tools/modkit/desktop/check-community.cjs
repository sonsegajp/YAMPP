const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const {setTimeout:delay}=require('node:timers/promises');
async function run({win,ROOT,CHECK_DIR}){
 await fs.mkdir(CHECK_DIR,{recursive:true});win.showInactive();
 const errors=[];win.webContents.on('console-message',(_event,level,message)=>{if(level>=3)errors.push(message)});
 const js=code=>win.webContents.executeJavaScript(code);
 const wait=async(code,timeout=150000)=>{const until=Date.now()+timeout;while(!await js(code)){if(Date.now()>until)throw new Error('UI wait failed: '+code+'; '+await js("document.querySelector('#status').textContent+' / '+document.querySelector('#community-message').textContent"));await delay(150)}};
 const capture=async name=>{await delay(400);await fs.writeFile(path.join(CHECK_DIR,name),(await win.webContents.capturePage()).toPNG())};
 await wait("document.querySelector('#status').textContent==='Captain Falcon loaded'");
 await js("document.querySelector('#costume-create').click();document.querySelector('#costume-pack-base').value='stock-Lk';document.querySelector('#costume-pack-base').dispatchEvent(new Event('change'));document.querySelector('#costume-pack-name').value='Workshop Community Check';[...document.querySelectorAll('#costume-pack-colors input')].forEach((c,i)=>c.checked=i<4)");
 await capture('create-four-costumes.png');
 await js("document.querySelector('#costume-pack-confirm').click()");
 await wait("document.querySelector('#status').textContent.startsWith('Costume pack created.')");
 await wait("document.querySelectorAll('.texture-card').length>10");
 assert.equal(await js("document.querySelector('#costume').options.length"),4);
 assert.equal(await js("document.querySelector('#asset-type').textContent"),'ADDITIONAL COSTUMES');
 assert.equal(await js("document.querySelector('[data-tab=lua]').hidden"),true);
 await capture('additive-costume-editor.png');
 const catalog=await js("window.workshop.request('/api/catalog')");
 const pack=catalog.fighters.find(f=>f.kind==='costume'&&f.name==='Workshop Community Check');assert(pack);
 await js("document.querySelector('#community-open').click()");
 await wait("document.querySelector('#community-message').textContent==='No matching costume packs.'");
 await js("document.querySelector('#community-publish-tab').click()");
 await wait("document.querySelector('#community-package').options.length===1");
 await js("document.querySelector('#community-description').value='Four extra Link colors, added alongside the original costumes.';document.querySelector('#community-author').value='Workshop Integration';document.querySelector('#community-prepare').click()");
 await wait("!document.querySelector('#community-review').hidden && !document.querySelector('#community-upload').disabled");
 assert.match(await js("document.querySelector('#community-review').textContent"),/4 additional colors/);
 await capture('review-upload.png');
 await js("document.querySelector('#community-upload').click()");
 await wait("document.querySelector('#community-message').textContent.startsWith('Pack published.')");
 await capture('published.png');
 const listed=await js("window.workshop.request('/api/community/catalog')");assert.equal(listed.mods.length,1);assert.equal(listed.mods[0].installed,true);
 // Move only this check's own source draft aside to exercise an actual download.
 const source=path.join(CHECK_DIR,'mods',pack.id),saved=path.join(CHECK_DIR,'author-draft');
 assert(source.startsWith(path.join(ROOT,'build/modkit')+path.sep));
 await fs.rename(source,saved);
 await js("document.querySelector('#community-browse-tab').click();document.querySelector('#community-refresh').click()");
 await wait("document.querySelector('[data-install-mod]')?.textContent==='Download & add costumes'");
 await capture('browse-published-pack.png');
 await js("document.querySelector('[data-install-mod]').click()");
 await wait("document.querySelector('#community-message').textContent.startsWith('Costumes added.')");
 await capture('installed-pack.png');
 const installed=await js("window.workshop.request('/api/community/catalog')");assert.equal(installed.mods[0].installed,true);assert.equal(installed.mods[0].enabled,true);
 const stamp=JSON.parse(await fs.readFile(path.join(source,'install.json'),'utf8'));assert.equal(stamp.sha256,listed.mods[0].sha256);assert.equal(Object.keys(stamp.files).length,4);
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(CHECK_DIR,'report.json'),JSON.stringify({passed:true,stockFighters:catalog.fighters.filter(f=>f.stock).length,additiveColors:4,sha256:stamp.sha256,checks:['create four additive costumes','stock gameplay stays read-only','real costume model and texture preview','prepare and review exact files','publish through private authenticated worker','browse published catalog','download and validate exact package','install enabled with hash provenance'],errors},null,2));
}
module.exports={run};
